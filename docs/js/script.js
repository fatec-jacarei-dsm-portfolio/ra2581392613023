const categoryLabels = {
  pt: { academic: 'Acadêmico', professional: 'Profissional', personal: 'Pessoal' },
  en: { academic: 'Academic', professional: 'Professional', personal: 'Personal' },
  es: { academic: 'Académico', professional: 'Profesional', personal: 'Personal' }
};

let currentLang = 'pt';
let currentFilter = 'all';

function t(key) {
  return translations[currentLang][key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    el.innerHTML = val;
  });
  
  // Atualiza o botão do dropdown
  document.getElementById('langFlag').textContent = langFlags[currentLang];
  document.getElementById('langLabel').textContent = currentLang.toUpperCase();
  document.documentElement.setAttribute('lang', currentLang === 'pt' ? 'pt-BR' : currentLang === 'es' ? 'es' : 'en');
  
  // Atualiza estado ativo no menu
  document.querySelectorAll('.lang-option').forEach(opt => {
    opt.classList.toggle('active', opt.dataset.lang === currentLang);
  });
  
  renderCards();
  updateFilterLabels();
}

function updateFilterLabels() {
  document.querySelectorAll('.filter-btn').forEach(btn => {
    const filter = btn.dataset.filter;
    const key = 'filter_' + filter;
    if (translations[currentLang][key]) {
      btn.textContent = translations[currentLang][key];
    }
  });
}

function renderCards() {
  const filtered = currentFilter === 'all'
    ? projectsData
    : projectsData.filter(p => p.category === currentFilter);
  
  const container = document.getElementById('cardsView');
  container.innerHTML = filtered.map(project => {
    const catLabel = categoryLabels[currentLang][project.category];
    const contributionItems = t(project.key + '_contribution');
    const contributionList = Array.isArray(contributionItems) 
      ? contributionItems.map(item => `<li>${item}</li>`).join('')
      : `<li>${contributionItems}</li>`;
    
    return `
      <article class="project-card">
        <div class="project-card-header ${project.category}">
          <div class="project-card-image" style="background-image: url('${project.image}')"></div>
          <div class="project-card-overlay">
            <div class="project-card-category">${catLabel}</div>
            <h3 class="project-card-title">${t(project.key + '_title')}</h3>
          </div>
        </div>
        <div class="project-card-body">
          <p class="project-card-desc">${t(project.key + '_desc')}</p>
          <div class="project-card-contribution" data-expanded="false">
            <h4 class="contribution-label">${t('proj_contribution_label')}</h4>
            <ul class="contribution-list">
              ${contributionList}
            </ul>
          </div>
          <div class="project-card-tech">
            ${t(project.key + '_tech').split(',').map(tech => `<span class="tech-pill">${tech.trim()}</span>`).join('')}
          </div>
          <div class="project-card-footer">
            <span>${t('proj_semester')}: ${t(project.key + '_sem')}</span>
            <div class="project-card-actions">
              <button class="project-card-toggle" aria-expanded="false">
                <span class="toggle-text">${t('proj_see_more')}</span>
              </button>
              <a href="${project.link}" class="project-card-link">${t('proj_see')}</a>
            </div>
          </div>
        </div>
      </article>
    `;
  }).join('');

  // Adiciona os event listeners nos novos botões
  container.querySelectorAll('.project-card-toggle').forEach(btn => {
    btn.addEventListener('click', () => {
      const card = btn.closest('.project-card');
      const contribution = card.querySelector('.project-card-contribution');
      const isExpanded = contribution.dataset.expanded === 'true';
      
      contribution.dataset.expanded = !isExpanded;
      btn.setAttribute('aria-expanded', !isExpanded);
      
      if (!isExpanded) {
        contribution.classList.add('expanded');
        btn.querySelector('.toggle-text').textContent = t('proj_see_less');
      } else {
        contribution.classList.remove('expanded');
        btn.querySelector('.toggle-text').textContent = t('proj_see_more');
      }
    });
  });
};

// ===== LANGUAGE DROPDOWN =====
const langDropdown = document.getElementById('langDropdown');
const langBtn = document.getElementById('langBtn');
const langMenu = document.getElementById('langMenu');
const langOptions = document.querySelectorAll('.lang-option');

// Abrir/fechar dropdown
langBtn.addEventListener('click', (e) => {
  e.stopPropagation();
  const isOpen = langDropdown.classList.contains('open');
  langDropdown.classList.toggle('open');
  langBtn.setAttribute('aria-expanded', !isOpen);
});

// Selecionar idioma
langOptions.forEach(option => {
  option.addEventListener('click', (e) => {
    e.stopPropagation();
    const newLang = option.dataset.lang;
    if (newLang !== currentLang) {
      currentLang = newLang;
      applyTranslations();
    }
    langDropdown.classList.remove('open');
    langBtn.setAttribute('aria-expanded', 'false');
  });
});

// Fechar ao clicar fora
document.addEventListener('click', (e) => {
  if (!langDropdown.contains(e.target)) {
    langDropdown.classList.remove('open');
    langBtn.setAttribute('aria-expanded', 'false');
  }
});

// Fechar com ESC
document.addEventListener('keydown', (e) => {
  if (e.key === 'Escape' && langDropdown.classList.contains('open')) {
    langDropdown.classList.remove('open');
    langBtn.setAttribute('aria-expanded', 'false');
  }
});
// ===== END LANGUAGE DROPDOWN =====

document.getElementById('themeBtn').addEventListener('click', () => {
  const current = document.documentElement.getAttribute('data-theme');
  const newTheme = current === 'light' ? 'dark' : 'light';
  document.documentElement.setAttribute('data-theme', newTheme);
  document.getElementById('themeIcon').textContent = newTheme === 'light' ? '🌙' : '☀️';
});

document.querySelectorAll('.filter-btn').forEach(btn => {
  btn.addEventListener('click', () => {
    document.querySelectorAll('.filter-btn').forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
    currentFilter = btn.dataset.filter;
    renderCards();
  });
});

const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
    }
  });
}, { threshold: 0.1, rootMargin: '0px 0px -50px 0px' });

document.querySelectorAll('.reveal').forEach(el => revealObserver.observe(el));

document.querySelectorAll('nav a, .hero-cta a').forEach(a => {
  a.addEventListener('click', (e) => {
    const href = a.getAttribute('href');
    if (href && href.startsWith('#')) {
      e.preventDefault();
      const target = document.querySelector(href);
      if (target) {
        target.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }
    }
  });
});

